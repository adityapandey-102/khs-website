// Builds src/data/categoryGalleries.ts: real, page-associated product photos
// (from the re-scraped asset manifest) per category, replacing the fabricated
// Unsplash-based products.ts. Run with `node scripts/build-category-galleries.mjs`
// after migrate-assets.mjs.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const BATHWARE_BUCKET_TO_CATEGORY = {
  "bathware/shower-faucets": "shower-faucets",
  "bathware/countertop-basin": "countertop-basin",
  "bathware/standalone-basin": "standalone-basin",
  "bathware/vanity-mirrors": "vanity-mirrors",
  "bathware/kitchen-sinks-faucets": "kitchen-sinks-faucets",
  "bathware/booster-heat-pumps": "booster-heat-pumps",
  "bathware/water-softeners-heaters": "water-softeners-heaters",
  "bathware/bath-accessories": "bath-accessories",
};

const LOGO_PATTERN = /logo|\bbrand\b|\/3m-?\d*\.(png|jpe?g|webp|gif)$/i;
// Bare small-integer filenames (1.png, 12-1.png, 3-2.png ...) are the
// signature of the reused brand-partner/clientele logo carousels, not
// page-specific product photography — WordPress attributes shared media to
// whichever page embeds it, so these need excluding from product galleries.
const NUMBERED_LOGO_PATTERN = /^\d{1,3}(-\d{1,2})?\.(png|jpe?g|webp|gif)$/i;

function isLikelyLogo(localPath) {
  const base = path.basename(localPath);
  return LOGO_PATTERN.test(localPath) || NUMBERED_LOGO_PATTERN.test(base);
}

function humanize(filename) {
  return path
    .basename(filename, path.extname(filename))
    .replace(/^(IMG|WhatsApp-Image|WA)[-_]?/i, "")
    .replace(/[-_]+/g, " ")
    .trim();
}

async function main() {
  const manifest = JSON.parse(
    await readFile(path.join(ROOT, "public/assets/khs/asset-map.json"), "utf8")
  );

  const galleries = {};

  for (const entry of manifest) {
    const categoryId = BATHWARE_BUCKET_TO_CATEGORY[entry.bucket];
    if (!categoryId) continue;
    if (isLikelyLogo(entry.localPath)) continue;
    const alt = entry.alt || entry.title || humanize(entry.localPath);
    (galleries[categoryId] ??= []).push({ src: entry.localPath, alt });
  }

  // Categories with no dedicated real photos on the old site fall back to the
  // real bathware hub page's photography rather than showing nothing.
  const hubImages = manifest
    .filter((e) => e.bucket === "bathware/_hub" && !isLikelyLogo(e.localPath))
    .map((e) => ({ src: e.localPath, alt: e.alt || e.title || "Krishna Home Studio bathware" }));

  for (const id of ["shower-enclosures", "spa-wellness", "washbasins-waterclosets-urinals"]) {
    galleries[id] = hubImages;
  }

  // Hardware: the old site never broke this into sub-categories (that's a
  // local addition), so every hardware page shares the one real hardware
  // photo collection rather than inventing a per-subcategory split.
  galleries.hardware = manifest
    .filter((e) => e.bucket === "hardware" && !isLikelyLogo(e.localPath))
    .map((e) => ({ src: e.localPath, alt: e.alt || e.title || "Krishna Home Studio hardware" }));

  const fileContent = `// AUTO-GENERATED by scripts/build-category-galleries.mjs from the re-scraped,
// page-associated asset manifest (public/assets/khs/asset-map.json). These are
// real Krishna Home Studio photographs, not stock imagery or invented products.
// Do not hand-edit; re-run the script to refresh after a fresh asset scrape.

export interface GalleryImage {
  src: string;
  alt: string;
}

export const categoryGalleries: Record<string, GalleryImage[]> = ${JSON.stringify(galleries, null, 2)};
`;

  await writeFile(path.join(ROOT, "src/data/categoryGalleries.ts"), fileContent, "utf8");

  console.log("Written to src/data/categoryGalleries.ts");
  for (const [id, images] of Object.entries(galleries)) {
    console.log(`  ${id}: ${images.length} photos`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
