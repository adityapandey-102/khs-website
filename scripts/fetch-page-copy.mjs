// Pulls the real, verbatim page copy from the live WordPress site for every
// confirmed page and writes it to src/data/pageCopy.ts as clean paragraph
// arrays, so page content on the new site is sourced from the actual old
// site rather than paraphrased. Run with `node scripts/fetch-page-copy.mjs`.

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SITE = "https://krishnahomestudio.com";

function decodeEntities(str) {
  return str
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&#8217;|&#039;|&rsquo;/g, "'")
    .replace(/&#8216;|&lsquo;/g, "'")
    .replace(/&#8220;|&ldquo;/g, '"')
    .replace(/&#8221;|&rdquo;/g, '"')
    .replace(/&#8211;|&ndash;/g, "-")
    .replace(/&#8212;|&mdash;/g, "-")
    .replace(/&#8230;|&hellip;/g, "...");
}

function htmlToParagraphs(html) {
  if (!html) return [];
  // Drop <style>/<script> blocks (Elementor inlines raw CSS/JS in page content)
  // before splitting on block-level closing tags and stripping remaining tags.
  const cleaned = html
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<script[\s\S]*?<\/script>/gi, " ");
  const chunks = cleaned.split(/<\/(?:p|h[1-6]|li)>/gi);
  const paragraphs = [];
  for (const chunk of chunks) {
    const text = decodeEntities(chunk.replace(/<[^>]+>/g, " "))
      .replace(/\s+/g, " ")
      .trim();
    if (text.length > 1 && !/^\.[a-z-]/i.test(text)) paragraphs.push(text);
  }
  return paragraphs;
}

async function fetchAllPages() {
  const items = [];
  let page = 1;
  for (;;) {
    const res = await fetch(`${SITE}/wp-json/wp/v2/pages?per_page=100&page=${page}`);
    if (!res.ok) {
      if (res.status === 400) break;
      throw new Error(`pages page ${page} failed: ${res.status}`);
    }
    const batch = await res.json();
    if (!Array.isArray(batch) || batch.length === 0) break;
    items.push(...batch);
    page += 1;
  }
  return items;
}

async function main() {
  console.log("Fetching all live pages ...");
  const pages = await fetchAllPages();
  console.log(`  ${pages.length} pages found.`);

  const result = {};
  for (const p of pages) {
    result[p.slug] = {
      id: p.id,
      title: decodeEntities((p.title?.rendered || "").replace(/<[^>]+>/g, "").trim()),
      paragraphs: htmlToParagraphs(p.content?.rendered || ""),
    };
  }

  const fileContent = `// AUTO-GENERATED by scripts/fetch-page-copy.mjs — real, verbatim copy pulled
// directly from the live krishnahomestudio.com WordPress site (wp-json/wp/v2/pages).
// Do not hand-edit; re-run the script to refresh.

export interface PageCopy {
  id: number;
  title: string;
  paragraphs: string[];
}

export const pageCopy: Record<string, PageCopy> = ${JSON.stringify(result, null, 2)};
`;

  await writeFile(path.join(ROOT, "src/data/pageCopy.ts"), fileContent, "utf8");
  console.log("Written to src/data/pageCopy.ts");
  for (const [slug, entry] of Object.entries(result)) {
    console.log(`  ${slug}: ${entry.paragraphs.length} paragraphs`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
